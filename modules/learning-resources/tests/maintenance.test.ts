test("停止排队或执行任务、总开关、定时开关、请求总上限与进度持久化", async () => {
  await sql`DELETE FROM resource_maintenance_checks`;
  await configure({ maxChecks: 0, maxCandidates: 3, maxRequests: 1, enabled: false });
  assert.deepEqual(await scheduleMaintenance(), { skipped: "自动维护关闭" });
  const id = (await createMaintenanceRun("test"))!;
  await stopMaintenance(id, "test");
  let calls = 0;
  await executeMaintenance(id, async () => { calls++; throw new Error("should not fetch"); });
  assert.equal(calls, 0);
  assert.equal((await maintenanceRun(id))!.status, "cancelled");
  const limited = (await executeMaintenance((await createMaintenanceRun("test"))!))!;
  assert.equal(limited.report.requests, 1);
  assert.equal(limited.report.created, 0);
  await sql`DELETE FROM resource_maintenance_checks`;
  const running = (await createMaintenanceRun("test"))!;
  let release!: () => void;
  let started!: () => void;
  const begun = new Promise<void>(resolve => { started = resolve; });
  const response = new Promise<void>(resolve => { release = resolve; });
  const execution = executeMaintenance(running, async () => { started(); await response; throw new Error("cancelled request"); });
  await begun;
  await stopMaintenance(running, "test");
  release();
  await execution;
  assert.equal((await maintenanceRun(running))!.status, "cancelled");
  assert.equal((await maintenanceRun(running))!.report.requests, 1);
  await sql`DELETE FROM resource_maintenance_checks`;
  const disabled = (await createMaintenanceRun("test"))!;
  process.env.COLLECT_ENABLED = "false";
  await executeMaintenance(disabled, async () => { calls++; throw new Error("should not fetch"); });
  assert.equal(calls, 0);
  assert.equal((await maintenanceRun(disabled))!.status, "cancelled");
  process.env.COLLECT_ENABLED = "true";
});
